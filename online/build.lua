-- General Public License v3.0 plus the additional attribution terms in
-- LICENSE.md. Not an official DriftJudging SP release; DriftFactory is not
-- affiliated with or endorsed by DeadEndReece.
-- Source, credits and license: https://github.com/insidedacoolest/drift-jury

local __bundled, __loaded = {}, {}
local __require = require
local function require(name)
  if __loaded[name] ~= nil then return __loaded[name] end
  local loader = __bundled[name]
  if not loader then return __require(name) end
  local value = loader()
  __loaded[name] = value == nil and true or value
  return __loaded[name]
end
]])

for _, name in ipairs(modules) do
  local code = read(srcDir .. name .. '.lua')
  emit(string.format('\n__bundled[%q] = function()\n%s\nend\n', 'src.' .. name, code))
end

emit('\n-- online/main.lua\n')
emit(read(repo .. '/online/main.lua'))

local target = repo .. '/online/driftfactory.lua'
local file = assert(io.open(target, 'wb'))
file:write(table.concat(out))
file:close()
print('wrote ' .. target)
