-- Builds online/driftfactory.lua: CSP loads an online script from a single
-- URL, so the app's modules are inlined ahead of online/main.lua.
-- Run from the repository root:  lua online/build.lua
local repo = (arg and arg[0] or ''):match('^(.*)[/\\]online[/\\]build%.lua$') or '.'
local srcDir = repo .. '/ac-lua/DriftFactoryJudgeApp/src/'

-- Every module the online script uses, in no particular order (each is
-- loaded lazily on first require).
local modules = {
  'util', 'defaults', 'geometry', 'profiles', 'model', 'results', 'scoring',
  'calibration', 'leaderboard', 'official_layout', 'session', 'editor',
  'draw', 'ui_app', 'context', 'storage_online',
}

local function read(path)
  local file = assert(io.open(path, 'rb'), 'missing ' .. path)
  local content = file:read('a')
  file:close()
  return (content:gsub('\r\n', '\n'))
end

local out = {}
local function emit(text) out[#out + 1] = text end

emit([[
-- Drift Factory Judge App — online script (GENERATED by online/build.lua,
-- do not edit by hand; edit online/main.lua or ac-lua/DriftFactoryJudgeApp/src).
--
-- A modified version of DriftJudging SP by DeadEndReece
